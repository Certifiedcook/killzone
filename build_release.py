"""Package the tested Kill Zone engine and desktop application."""

from __future__ import annotations

import argparse
import shutil
from pathlib import Path

from src.release_tools import copy_engine, recreate_generated_directory, write_zip

ROOT = Path(__file__).resolve().parent
RELEASE_MARKER = ".killzone-generated-release"
SUPPORT_FILES = (
    "README.md",
    "ASSET_SOURCES.md",
    "requirements.txt",
    "launch_kill_zone.bat",
    "validate.bat",
    "validate.py",
    "regression_test.py",
    "runtime_smoke_test.py",
    "multiplayer_test.py",
    "presentation_test.py",
    "combat2_test.py",
    "combat_polish_test.py",
    "stress_test.py",
    "benchmark.py",
    "self_test.py",
    "ui_smoke_test.py",
    "benchmark_test.py",
    "performance_test.py",
    "spatial_test.py",
    "clock_test.py",
    "engine_test.py",
    "engine_cli_test.py",
    "scenario_test.py",
    "state_test.py",
    "ARCHITECTURE.md",
    "ENGINE_TOOLS.md",
    "ROADMAP.md",
)


def build_release(output: Path):
    recreate_generated_directory(
        output,
        RELEASE_MARKER,
        "Generated by build_release.py\n",
    )
    copy_engine(ROOT, output)
    (output / "multiplayer_server").mkdir(exist_ok=True)
    shutil.copy2(ROOT / "multiplayer_server" / "app.py", output / "multiplayer_server" / "app.py")
    shutil.copy2(
        ROOT / "multiplayer_server" / "requirements.txt",
        output / "multiplayer_server" / "requirements.txt",
    )
    for name in SUPPORT_FILES:
        shutil.copy2(ROOT / name, output / name)
def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("output", nargs="?", type=Path, default=ROOT / "build" / "kill_zone_release")
    parser.add_argument("--zip", action="store_true", dest="make_zip")
    args = parser.parse_args()
    output = args.output.resolve()
    build_release(output)
    print(f"Release materialized at {output}")
    if args.make_zip:
        destination = output.with_suffix(".zip")
        write_zip(output, destination, include_root=True)
        print(f"Release archive written to {destination}")


if __name__ == "__main__":
    main()
